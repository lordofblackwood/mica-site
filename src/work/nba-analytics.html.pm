◊project-meta[#:status "concept" #:kind "data product"]

◊lede{A product direction for asking basketball questions in ordinary language and receiving useful queries, dashboards, visualizations, and explanations.}

◊p{The idea is to bridge raw NBA data and the questions coaches, analysts, podcasters, and fans actually ask. Instead of requiring users to know a database schema, the system would translate a question into a query, show the supporting chart or table, and explain how it reached the result.}

◊section-title{Possible features}

◊ul{
  ◊li{Natural-language questions grounded in NBA data.}
  ◊li{Generated dashboards and visualizations.}
  ◊li{Translation tables that map basketball concepts to concrete data fields.}
  ◊li{Retrieved context for metric definitions and player or team history.}
  ◊li{Exportable charts for reports, podcasts, and presentations.}
}

◊note{◊p{This page describes a concept and prototype direction, not a finished public product.}}
