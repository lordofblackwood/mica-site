◊lede{A computational text-analysis project studying how the Acts of Andrew may reconfigure the model of Jesus toward ascetic and possibly dualist theological signals.}

◊p{The project compares three corpora: the canonical Gospels; the Gospels plus the Acts of Andrew; and the Gospels plus Gregory of Tours’ orthodox-filtered recension. The goal is to test how adding or filtering a text changes the visible theological signal around Jesus.}

◊section-title{Method}

◊ul{
  ◊li{Define theological propositions around Encratic and Manichaean themes.}
  ◊li{Retrieve passages that may bear on those propositions across each corpus.}
  ◊li{Score passages for support, contradiction, ambiguity, or neutrality.}
  ◊li{Aggregate proposition-level results by corpus and inspect the differences.}
  ◊li{Use the results alongside close reading, not as a substitute for it.}
}

◊section-title{Why it matters}

◊p{The project treats canon formation and redaction as a possible signal-filtering process. Communities do not merely preserve texts; they may amplify, soften, redirect, or suppress theological signals. A careful computational comparison can make some of those shifts easier to inspect while keeping the interpretive limits visible.}
